/** 駅から東京までの分岐点の並び（経路距離の計算用） */
export function hubPath(st) {
  switch (st.line) {
    case 'W': return ['東京'];
    case 'N': return ['武雄温泉', '博多', '東京'];
    case 'T': return [...(st.lat > 39.71 ? ['盛岡'] : []), ...(st.lat > 37.76 ? ['福島'] : []), '大宮', '東京'];
    case 'Y': return ['福島', '大宮', '東京'];
    case 'A': return ['盛岡', '福島', '大宮', '東京'];
    case 'J': return ['高崎', '大宮', '東京'];
    case 'H': return ['高崎', '大宮', '東京'];
    default: return ['東京'];
  }
}
